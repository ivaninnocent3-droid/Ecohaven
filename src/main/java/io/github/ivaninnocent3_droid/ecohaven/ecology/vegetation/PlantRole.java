package io.github.ivaninnocent3_droid.ecohaven.ecology.vegetation;

/**
 * Ecological role played by a plant in its local vegetation community.
 */
public enum PlantRole {

    /**
     * Low-growing vegetation that occupies open ground.
     */
    GROUND_COVER,

    /**
     * Plants that are particularly suited to growing beneath trees
     * and other sources of shade.
     */
    UNDERSTORY,

    /**
     * Distinctive flora restricted to the biome profiles that include it.
     */
    SPECIAL
}